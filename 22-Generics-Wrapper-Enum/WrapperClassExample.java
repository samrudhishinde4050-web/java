public class WrapperClassExample {

    public static void main(String[] args) {

        Integer number = 100;
        Double price = 99.50;
        Character grade = 'A';
        Boolean status = true;

        System.out.println("Integer: " + number);
        System.out.println("Double: " + price);
        System.out.println("Character: " + grade);
        System.out.println("Boolean: " + status);
    }
}
